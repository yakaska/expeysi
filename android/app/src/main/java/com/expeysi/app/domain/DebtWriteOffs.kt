 * считается доходом, минус — расходом, поэтому списание живёт в доходной
 * или расходной разрезке собственной строкой [CATEGORY_ID], а записи в БД
 * за ним нет. Не открывается, как и комиссии переводов ([TransferFees]).
 */
object DebtWriteOffs {

    /** id псевдо-категории и псевдо-«счёта» списаний в агрегатах. */
    const val CATEGORY_ID = "debt-write-offs"

    /**
     * Ключ иконки списания в разрезках — тот же, что у строки «Списание»
     * в истории долга (Block). Literal один: IconCatalog ссылается на ключ.
     */
    const val ICON_KEY = "block"

    /** Нейтральный цвет из палитры категорий. */
    const val COLOR_KEY = "default"
}
