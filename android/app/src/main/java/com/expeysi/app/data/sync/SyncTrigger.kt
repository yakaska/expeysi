package com.expeysi.app.data.sync

/**
 * Шов для мест записи (UI): запускает перенос dirty-строк Room в удалённый
 * журнал. Сами строки перед вызовом уже обязаны лежать в Room с флагом
 * dirty — обычно записью entity с dirty = true.
 */
interface SyncTrigger {

    /**
     * Ставит запрос прохода в conflated-канал воркера движка и возвращается
     * сразу, не дожидаясь отправки (инвариант 5): N подряд вызовов дают не
     * более одного лишнего прохода; сеть никогда не вызывается из контекста
     * вызывающего.
     */
    fun trigger()
}
