package com.expeysi.app.data.remote

/**
 * Семейные мутации в удалённом хранилище.
 *
 * Контракт повторяет поведение текущего Firebase-транспорта (инвариант 6):
 * - [createFamily] и [joinFamily] возвращаются, НЕ дожидаясь подтверждения
 *   записи сервером: мутация отправляется и остаётся в офлайн-очереди, пока
 *   нет сети. Приложение уже выбрало семью локально и дальше работает.
 *   РИСК для будущей HTTP-реализации: ей придётся ждать ответ сервера — иначе
 *   familyId или код приглашения может ещё не существовать на сервере в момент,
 *   когда второй участник попытается вступить.
 * - [leaveFamily], наоборот, ждёт подтверждения удаления членства; таймаут
 *   задаёт снаружи [com.expeysi.app.data.FamilyRepository] (10 с), при сбое
 *   локальный выход всё равно выполняется.
 */
interface FamilyRemote {

    /** Создаёт документ семьи и своё членство; возвращает familyId. */
    suspend fun createFamily(uid: String, displayName: String): String

    /** Создаёт документ своего членства в существующей семье. */
    suspend fun joinFamily(familyId: String, uid: String, displayName: String)

    /** Удаляет своё членство; ждёт подтверждения (таймаут — снаружи). */
    suspend fun leaveFamily(familyId: String, uid: String)
}
