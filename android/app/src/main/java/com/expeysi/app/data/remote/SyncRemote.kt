package com.expeysi.app.data.remote

import kotlinx.coroutines.flow.Flow

/**
 * Журнал изменений семьи в удалённом хранилище.
 *
 * - [observe] — один поток всех типов семьи. Реализация сама переподключается
 *   после ошибок (пауза 5 с) и не пробрасывает исключения наружу. Обновления
 *   могут быть полным состоянием типа или только дельтой
 *   (RemoteUpdate.isFullState).
 * - [push] — передаёт изменения транспорту и возвращает ключи, принятые к
 *   доставке («accepted»). Реализация сама режет отправку на порции; при
 *   сбое либо бросает исключение (ничего не принято), либо возвращает
 *   частичный accepted — часть порций ушла, остальные нет. Повторная
 *   отправка уже принятого изменения безопасна (идемпотентна).
 *   Семантика accepted: для Firebase — «передано SDK / офлайн-очереди
 *   транспорта» (инвариант 5); для будущего HTTP-транспорта — «принято
 *   сервером» (реализация обязана ждать ответ и сама хранить очередь
 *   недоставленного).
 *
 * Все методы принимают familyId явно и вызываются только с непустым идентификатором:
 * без выбранной семьи потребитель ничего не отправляет и не слушает.
 * Сущность поля SyncChange.fields — полный wire-формат (docs/data-model.md),
 * включая deleted/updatedAt, без id (id в SyncKey) и без локального dirty.
 */
interface SyncRemote {

    /**
     * Поток обновлений всех типов выбранной семьи. Транспорт сам переживает
     * разрывы связи (Firebase: переподключение через 5 с после ошибки);
     * исключения наружу не пробрасываются.
     */
    fun observe(familyId: String): Flow<RemoteUpdate>

    /**
     * Передаёт изменения транспорту и возвращает ключи, принятые к доставке.
     * Реализация сама режет отправку на порции; детали семантики accepted —
     * в KDoc интерфейса.
     */
    suspend fun push(familyId: String, changes: List<SyncChange>): PushResult

    /**
     * Ключи, чья запись была принята транспортом к доставке (попала в
     * accepted), но позже отклонена сервером. Отказ до начала доставки сюда не
     * попадает: он отражается в accepted (ключ не принят) или в исключении
     * push. Потребитель помечает отклонённые строки dirty и повторяет отправку.
     *
     * Для транспорта, который ждёт ответ сервера (HTTP), поток пустой:
     * отклонённые записи не включаются в accepted, и после доставки сервер
     * уведомляет потребителей через observe. Транспорт с отложенной доставкой
     * (Firebase) обязан не терять события: внутренний буфер потока.
     */
    val rejections: Flow<SyncKey>
}
