package com.expeysi.app.data.remote

import kotlinx.coroutines.flow.Flow

/**
 * Журнал изменений семьи в удалённом хранилище. Контракт отражает поведение
 * текущего Firebase-транспорта (инвариант 5):
 * - [observeChanges] — realtime-снимки; транспорт обязан сообщать полное
 *   состояние типа (RemoteUpdate.isFullState) и сам переживать разрывы связи;
 * - [postChange] — одиночное изменение, отправляется БЕЗ ожидания
 *   подтверждения: запись попадает в офлайн-очередь и доставится, когда
 *   появится сеть. РИСК для будущей HTTP-реализации: ей придётся либо ждать
 *   ответ сервера, либо завести собственную очередь недоставленного.
 * - [uploadBulk] — массовая загрузка импорта: батчи по 500 документов;
 *   первые батчи ждут подтверждения с таймаутом, заданным параметром
 *   [uploadBulk]; после первого таймаута остальные отправляются без ожидания.
 *   Прочие ошибки пробрасываются вызывающему.
 *
 * Все методы принимают familyId явно и вызываются только с непустым идентификатором:
 * без выбранной семьи потребитель ничего не отправляет и не слушает.
 * Сущность поля SyncChange.fields — полный wire-формат (docs/data-model.md),
 * включая deleted/updatedAt, без id (id в SyncKey) и без локального dirty.
 */
interface SyncRemote {

    /**
     * Поток снимков одного типа сущностей выбранной семьи. Каждый снимок
     * содержит полное состояние типа; транспорт обязан переживать разрывы
     * связи сам (Firebase: переподключение через 5 с после ошибки).
     */
    fun observeChanges(familyId: String, type: SyncEntityType): Flow<RemoteUpdate>

    /** Отправляет одиночное изменение; подтверждения не ждёт (инвариант 5). */
    suspend fun postChange(familyId: String, change: SyncChange)

    /**
     * Массовая загрузка импортированных данных батчами по 500. Первый таймаут
     * подтверждения переводит оставшиеся батчи в режим без ожидания.
     */
    suspend fun uploadBulk(familyId: String, changes: List<SyncChange>, timeoutMillis: Long)
}
